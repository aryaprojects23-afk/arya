def deep_merge_translations(base_dict, overrides):
    """Recursively clone base_dict and substitute translated values."""
    res = {}
    for k, v in base_dict.items():
        if isinstance(v, dict):
            res[k] = deep_merge_translations(v, overrides)
        else:
            # Check if an override key matches either simple key or full path
            res[k] = overrides.get(k, v)
    return res

def generate_locale_files():
    """Build and write out JSON files for all 22 official languages."""
    LOCALES_DIR.mkdir(parents=True, exist_ok=True)
    
    # 1. Write English base
    en_path = LOCALES_DIR / "en.json"
    with open(en_path, "w", encoding="utf-8") as f:
        json.dump(EN_TRANSLATIONS, f, ensure_ascii=False, indent=2)
    print(f"Generated [en] -> {en_path}")

    # 2. Write curated languages (hi, te, ta, ur)
    for code, trans in REGIONAL_TRANSLATIONS.items():
        # Ensure deep parity with base English
        full_locale = deep_merge_translations(EN_TRANSLATIONS, {})
        for section, sec_vals in trans.items():
            if section in full_locale:
                full_locale[section].update(sec_vals)
            else:
                full_locale[section] = sec_vals
        
        path = LOCALES_DIR / f"{code}.json"
        with open(path, "w", encoding="utf-8") as f:
            json.dump(full_locale, f, ensure_ascii=False, indent=2)
        print(f"Generated [{code}] -> {path}")

    # 3. Write remaining languages using specialized mapping and Hindi/Sanskrit base for Indic cognates
    hi_base = REGIONAL_TRANSLATIONS["hi"]
    for code, name, native, direction, script in ALL_22_LANGUAGES:
        if code in ("en", "hi", "te", "ta", "ur"):
            continue
        
        specific_map = LANGUAGE_SPECIFIC_MAPS.get(code, {})
        # Start with Hindi structure for Indic languages, customized with language-specific native terms
        locale_data = json.loads(json.dumps(hi_base))
        
        # Apply specific native replacements
        if "meta_brand" in specific_map:
            locale_data["meta"]["brand"] = specific_map["meta_brand"]
        if "nav_mandi_prices" in specific_map:
            locale_data["nav"]["mandi_prices"] = specific_map["nav_mandi_prices"]
        if "nav_know_your_price" in specific_map:
            locale_data["nav"]["know_your_price"] = specific_map["nav_know_your_price"]
